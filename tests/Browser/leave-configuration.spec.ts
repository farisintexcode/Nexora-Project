import { expect, test } from './fixtures';

test('authorized HR configures leave availability and Riders see only active types', async ({ page, browser }) => {
    test.setTimeout(240000);
    const password = process.env.DCMS_E2E_PASSWORD;
    test.skip(!password, 'Requires isolated BrowserTestSeeder fixtures.');
    const failures: string[] = [];
    page.on('pageerror', error => failures.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    const name = `Browser Leave ${test.info().project.name} ${Date.now()}`;
    await page.goto('/login');
    await page.getByLabel('Email', { exact: true }).fill('hr-admin@example.test');
    await page.getByLabel('Password', { exact: true }).fill(password!);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(page).toHaveURL(/\/admin$/);
    await page.goto('/admin/leave/types');
    await expect(page.getByRole('heading', { name: 'Leave Types & Entitlements', exact: true })).toBeVisible();
    await page.getByLabel('Leave Type Name', { exact: true }).fill(name);
    await page.getByLabel('Maximum Calendar Span (days)', { exact: true }).fill('7');
    await page.getByLabel('Allow Rider to cancel a pending application', { exact: true }).check();
    await page.getByRole('button', { name: 'Save Leave Type', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Leave type saved' })).toBeVisible();
    await page.getByRole('button', { name: 'OK', exact: true }).click();
    const card = page.getByRole('article').filter({ hasText: name });
    await card.getByRole('button', { name: `Edit Type ${name}`, exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Edit Leave Type', exact: true })).toBeVisible();
    await expect(page.getByLabel('Maximum Calendar Span (days)', { exact: true })).toHaveValue('7');
    await page.getByLabel('Maximum Calendar Span (days)', { exact: true }).fill('3');
    await page.getByRole('button', { name: 'Save Leave Type', exact: true }).click();
    await expect(card).toContainText('3 calendar-day span');
    await page.getByRole('button', { name: 'OK', exact: true }).click();
    await card.getByRole('button', { name: `Deactivate ${name}`, exact: true }).click();
    await expect(card).toContainText('Inactive', { timeout: 30000 });
    await page.getByRole('button', { name: 'OK', exact: true }).click();
    const riderContext = await browser.newContext();
    const riderPage = await riderContext.newPage();
    riderPage.on('pageerror', error => failures.push(error.message));
    await riderPage.goto(`${process.env.PLAYWRIGHT_BASE_URL || 'http://127.0.0.1:8000'}/rider/login`);
    await riderPage.getByLabel('Email', { exact: true }).fill('rider@example.test');
    await riderPage.getByLabel('Password', { exact: true }).fill(password!);
    await riderPage.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(riderPage).toHaveURL(/\/rider$/);
    await riderPage.goto(`${process.env.PLAYWRIGHT_BASE_URL || 'http://127.0.0.1:8000'}/rider/attendance/leave/apply`);
    await expect(riderPage.getByLabel('Leave Type', { exact: true }).getByRole('option', { name, exact: true })).toHaveCount(0);
    expect((await riderContext.request.get(`${process.env.PLAYWRIGHT_BASE_URL || 'http://127.0.0.1:8000'}/admin/leave/types`)).status()).toBe(403);
    await card.getByRole('button', { name: `Activate ${name}`, exact: true }).click();
    await expect(card).toContainText('Active', { timeout: 30000 });
    await page.getByRole('button', { name: 'OK', exact: true }).click();
    await riderPage.reload();
    await expect(riderPage.getByLabel('Leave Type', { exact: true }).getByRole('option', { name, exact: true })).toHaveCount(1);
    await page.evaluate(() => window['dcmsSetTheme']('dark'));
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(failures).toEqual([]);
    await riderContext.close();
});
