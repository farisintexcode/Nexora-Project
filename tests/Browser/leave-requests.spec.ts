test('Admin configures actual leave rules and records a rejection reason', async ({ page }) => {
    page.on('dialog', dialog => dialog.accept());
    await login(page, true);
    await page.goto('/admin/leave');
    await page.goto('/admin/leave/types');
    await page.getByLabel('Leave Type Name', { exact: true }).fill(`Synthetic Emergency ${test.info().project.name} ${Date.now()}`);
    await page.getByLabel('Maximum Calendar Span (days)', { exact: true }).fill('7');
    await page.getByLabel('Allow applications for past dates', { exact: false }).check();
    await page.getByLabel('Allow Rider to cancel a pending application', { exact: true }).check();
    await page.getByRole('button', { name: 'Save Leave Type' }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Leave type saved' })).toBeVisible();
    await page.getByRole('button', { name: 'OK', exact: true }).click();
    await page.goto('/admin/leave');
    const offset = test.info().project.name === 'desktop' ? 5 : 8;
    const date = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Kuala_Lumpur', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date(Date.now() + offset * 86400000));
    await chooseDateRange(page, 'leave-date', 'Date', date);
    await page.getByLabel('Status', { exact: true }).selectOption('pending');
    await page.getByRole('button', { name: 'Apply Filters' }).click();
    await expect(page.getByRole('link', { name: 'View Request', exact: true })).toHaveCount(1);
    await page.getByRole('link', { name: 'View Request', exact: true }).click();
    await page.getByLabel('Decision', { exact: true }).selectOption('rejected');
    await page.getByLabel('Admin Remarks / Rejection Reason').fill('Synthetic staffing conflict; please choose another date.');
    await page.getByRole('button', { name: 'Confirm Decision' }).click();
    await page.getByRole('dialog', { name: 'Save this leave decision?', exact: true }).getByRole('button', { name: 'Confirm', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'decision has been saved' })).toBeVisible();
    await page.getByRole('button', { name: 'OK', exact: true }).click();
    await expect(page.getByText('Rejected', { exact: true })).toBeVisible();
    await expect(page.getByText('Synthetic staffing conflict; please choose another date.', { exact: true })).toBeVisible();
    await page.screenshot({ path: test.info().outputPath('admin-leave-rejected.png'), fullPage: true });
});
