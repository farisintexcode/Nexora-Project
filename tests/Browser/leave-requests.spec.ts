import { chooseDateRange, expect, test, type Page } from './fixtures';

async function login(page: Page, admin = false) {
    await page.goto(admin ? '/login' : '/rider/login');
    await page.getByLabel('Email', { exact: true }).fill(admin ? process.env.DCMS_E2E_ADMIN_EMAIL! : process.env.DCMS_E2E_RIDER_EMAIL!);
    await page.getByLabel('Password', { exact: true }).fill(process.env.DCMS_E2E_PASSWORD!);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(page).toHaveURL(admin ? /\/admin$/ : /\/rider$/);
}
async function logout(page: Page) {
    await page.getByRole('button', { name: 'Profile', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Logout', exact: true }).click();
    await expect(page).toHaveURL(/\/rider\/login$/);
}

