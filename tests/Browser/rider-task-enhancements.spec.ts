import { expect, test } from './fixtures';

test('Rider completes a short visit with stamped proof and immediately sees assignment progress', async ({ page, context }) => {
    test.setTimeout(120000);
    const email = process.env.DCMS_E2E_RIDER_EMAIL;
    const password = process.env.DCMS_E2E_PASSWORD;
    test.skip(!email || !password, 'Use isolated synthetic Rider fixtures.');
    const surface = test.info().project.name;
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    const sample = await context.newPage();
    await sample.setViewportSize({ width: 1200, height: 800 });
    await sample.setContent('<div style="position:fixed;inset:0;background:#cbd5df;display:grid;place-items:center;font:40px sans-serif;color:#023047">Synthetic premises photo</div>');
    const photo = await sample.screenshot();
    await sample.close();

    await page.goto('/rider/login');
    await page.getByLabel('Email', { exact: true }).fill(email!);
    await page.getByLabel('Password', { exact: true }).fill(password!);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(page).toHaveURL(/\/rider$/);
    await page.goto('/rider/assignments');
    const card = page.locator('article').filter({ hasText: `Synthetic Rider Batch ${surface}` });
    await expect(card).toContainText('2 of 3 completed');
    await page.goto('/rider/tasks');
    await page.getByLabel('Account or customer reference', { exact: true }).fill(`M06-${surface.toUpperCase()}`);
    await page.getByRole('button', { name: 'Search', exact: true }).click();
    await expect(page.getByRole('link', { name: 'View Task', exact: true })).toHaveCount(1);
    await page.getByRole('link', { name: 'View Task', exact: true }).click();
    await page.getByRole('button', { name: 'Start Task', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Field Visit Details', exact: true })).toBeVisible();
    await page.getByLabel('Visit outcome', { exact: true }).selectOption('successful_visit');
    await page.getByLabel('Customer availability', { exact: true }).selectOption('available');
    await page.getByLabel('Site status', { exact: true }).selectOption('operating');
    await page.getByLabel('Contact result', { exact: true }).selectOption('customer_contacted');
    await page.getByLabel('Remarks / Notes', { exact: true }).fill('Synthetic short visit recorded.');
    const additional = page.locator('details').filter({ has: page.locator('summary').filter({ hasText: 'Additional Details' }) });
    if (await additional.getAttribute('open') === null) await page.getByText('Additional Details', { exact: true }).click();
    await page.getByLabel('Site address / location', { exact: true }).fill('10 Synthetic Field Road');
    await page.getByText('Additional Details', { exact: true }).click();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: test.info().outputPath('short-visit-form.png'), fullPage: true });
    await page.getByRole('button', { name: 'Save visit & remarks', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Proof Picture', exact: true })).toBeVisible();
    await page.getByLabel('Choose images from camera or gallery', { exact: true }).setInputFiles({ name: 'premises.png', mimeType: 'image/png', buffer: photo });
    await expect(page.getByRole('img', { name: 'Selected image preview · not yet scanned', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Upload selected images', exact: true }).click();
    await expect(page.getByText('Images saved privately.', { exact: true })).toBeVisible();
    await expect(page.getByText('Skipped', { exact: true })).toHaveCount(0);
    const proof = page.getByRole('img', { name: 'Categorized task proof', exact: true });
    await expect(proof).toBeVisible();
    await expect.poll(() => proof.evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true);
    await proof.evaluate(image => image.scrollIntoView({ block: 'center' }));
    await proof.screenshot({ path: test.info().outputPath('watermarked-proof.png') });
    await page.getByRole('button', { name: 'Complete Task', exact: true }).click();
    await expect(page.getByText('Required checks passed.', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Complete Task', exact: true }).click();
    await page.getByRole('dialog', { name: 'Complete this task?', exact: true }).getByRole('button', { name: 'Confirm', exact: true }).click();
    await expect(page.getByText('Task completed and submitted. Awaiting Admin verification', { exact: false })).toBeVisible();
    await page.goto('/rider/assignments');
    await expect(card).toContainText('3 of 3 completed');
    await expect(card).toContainText('0 pending');
    await expect(card.getByRole('progressbar', { name: 'Completed tasks' })).toHaveAttribute('aria-valuenow', '100');
    await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' });
    await expect(page.locator('html')).toHaveClass(/dark/);
    await expect(card).toHaveCSS('background-color', 'rgb(16, 54, 71)');
    await page.screenshot({ path: test.info().outputPath('submitted-progress-dark.png'), fullPage: true });
    expect(errors).toEqual([]);
});
